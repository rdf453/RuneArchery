/*
 * 5. RAIDHO (라이도) - ᚱ
 *    - [정위치 (Upright)]
 *      · 상징: 순조로운 여정, 마차, 이동, 올바른 방향, 진척
 *      · 해석: 여행이나 이사 같은 실제 이동뿐 아니라
 *        계획이 다음 단계로 나아가는 흐름을 나타낸다.
 *        목적지만 바라보기보다 일정과 동행자,
 *        자신이 지키려는 원칙이 서로 맞는지 살피면 여정이 한결 안정된다.
 *        속도가 빠르지 않더라도 방향이 맞고 꾸준히 움직인다면
 *        이미 진전은 시작된 것이다.
 *    - [역위치 (Reversed)]
 *      · 상징: 여정의 지연, 방해, 방향 상실, 잘못된 선택, 고장
 *      · 해석: 지연과 우회가 생겼다면 무조건 밀어붙이기보다
 *        계획의 전제와 이동 경로를 재점검하라.
 *        일정의 어긋남은 준비가 부족하다는 신호일 수도 있고,
 *        애초에 목적지가 자신에게 맞지 않는다는 질문일 수도 있다.
 *        잠시 멈춰 방향을 바로잡는 선택은 실패가 아니라
 *        더 큰 낭비를 막는 조정이다.
 */
