/*
 * 18. BERKANO (베르카노) - ᛒ
 *    - [정위치 (Upright)]
 *      · 상징: 자작나무, 새로운 시작, 어머니의 치유, 성장, 포용
 *      · 해석: 아직 여린 싹을 보살피듯 새로운 관계와 계획,
 *        몸과 마음의 회복이 보호받으며 자랄 수 있다.
 *        성장에는 안전한 환경과 꾸준한 돌봄이 필요하므로
 *        빠른 성과보다 작은 변화를 알아보라.
 *        자신을 돌보는 일과 다른 이를 품는 일이 서로 소진시키지 않도록
 *        따뜻함과 경계를 함께 지키는 것이 좋다.
 *    - [역위치 (Reversed)]
 *      · 상징: 성장의 정체, 가정 불화, 치유 지연, 미숙함, 썩은 뿌리
 *      · 해석: 겉으로는 자라고 있는 듯 보여도
 *        오래된 갈등이나 돌보지 못한 상처가 뿌리에서 성장을 막을 수 있다.
 *        결과를 재촉하거나 미숙함을 부끄러워하기보다
 *        무엇이 안전과 양분을 빼앗고 있는지 살펴라.
 *        필요한 경계를 세우고 근본 원인을 돌보는 시간이 들더라도,
 *        회복은 다시 자랄 토양을 만드는 과정이다.
 */
