/*
 * 12. JERA (예라) - ᛃ
 *    - [정위치 (Upright)]
 *      · 상징: 1년의 순환, 수확, 노력에 대한 결실, 타이밍
 *      · 해석: 씨를 뿌리고 돌본 시간이 지나
 *        계절에 맞는 결실을 거두는 흐름이다.
 *        결과가 하루아침에 생긴 것처럼 보여도
 *        그 뒤에는 반복된 노력과 알맞은 시기를 기다린 시간이 놓여 있다.
 *        성과를 누리는 동시에 다음 순환을 준비하고,
 *        지금의 결과가 어떤 선택에서 비롯되었는지 배워 두라.
 *    - [역위치 (Reversed)]
 *      · 상징: 시간 낭비, 수확의 실패, 타이밍 어긋남, 헛수고
 *      · 해석: 기대한 결과가 늦어지거나 노력과 보상이 맞지 않는 듯해도,
 *        무조건 더 오래 버티는 것이 답은 아닐 수 있다.
 *        계절이 아직 무르익지 않았는지,
 *        씨앗과 토양 또는 목표 자체가 맞는지 점검하라.
 *        이미 쓴 시간에 매달리기보다 방향을 조정하고
 *        새로운 주기를 시작하는 편이 앞으로의 시간을 살릴 수 있다.
 */
