/*
 * 24. OTHALA (오탈라) - ᛟ
 *    - [정위치 (Upright)]
 *      · 상징: 유산, 고향, 혈통, 소유지, 전통
 *      · 해석: 자신이 어디에서 왔고 무엇을 물려받았는지 돌아보며,
 *        그 유산을 어떻게 이어 갈지 선택할 때다.
 *        유산은 재산뿐 아니라 언어와 습관, 가족의 기억,
 *        공동체가 지켜 온 지혜일 수 있다.
 *        전통을 무조건 반복하기보다 자신에게 힘이 되는 것은 보존하고
 *        다음 세대에 남길 의미를 새롭게 만들어라.
 *    - [역위치 (Reversed)]
 *      · 상징: 유산 분쟁, 고향 상실, 가족 간의 갈등, 구시대적 집착, 단절
 *      · 해석: 물려받은 기대와 자신의 삶이 충돌하거나,
 *        소속감을 둘러싼 갈등과 상실감이 드러날 수 있다.
 *        혈연과 전통이라는 이유만으로 불공정한 요구를 받아들일 필요는 없지만,
 *        과거를 단순히 끊어 내기 전에
 *        무엇이 상처이고 무엇이 지킬 가치인지 구분하라.
 *        자신이 선택한 관계와 공간에서도
 *        새로운 의미의 고향을 만들 수 있다.
 */
