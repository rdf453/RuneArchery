/*
 * 13. EIHWAZ (에이와즈) - ᛇ
 *    - [정위치 (Upright)]
 *      · 상징: 주목나무, 세계수, 불변의 경계, 인내, 영속성
 *      · 해석: 뿌리와 가지가 서로 다른 세계를 잇는 나무처럼,
 *        이 룬은 변화 속에서도 중심을 지키는 힘을 말한다.
 *        넘어야 할 문턱이 높아 보여도 서두르지 않고 준비를 이어 가면
 *        오래 버틸 기반이 생긴다.
 *        인내는 아무것도 하지 않는 태도가 아니라,
 *        중요한 가치를 놓치지 않으면서 적절한 순간을 기다리는 적극적인 자세다.
 *    - [역위치 (Reversed)]
 *      · 상징: 두려움, 변화에 대한 거부, 방향성 상실, 연약함
 *      · 해석: 안전을 지키려는 마음이 변화를 막는 벽이 되었거나,
 *        반대로 방향을 잃어 작은 흔들림에도 자신이 무너질 것처럼 느껴질 수 있다.
 *        두려움을 없애려고 애쓰기보다 무엇을 잃을까 걱정하는지 이름 붙이고,
 *        지금 지킬 것과 놓아줄 것을 구별하라.
 *        유연하게 방향을 다시 잡는 일은 뿌리를 버리는 일이 아니다.
 */
