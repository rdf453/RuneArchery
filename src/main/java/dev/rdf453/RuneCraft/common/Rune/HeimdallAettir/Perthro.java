/*
 * 14. PERTHRO (페르드로) - ᛈ
 *    - [정위치 (Upright)]
 *      · 상징: 운명, 비밀, 숨겨진 재능, 확률의 수수께끼, 주사위
 *      · 해석: 아직 알려지지 않은 정보와 우연한 만남이
 *        새로운 가능성을 열 수 있다.
 *        결과를 완전히 통제할 수는 없지만,
 *        자신 안에 숨어 있던 재능을 발견하고
 *        어떤 위험을 감수할지 선택할 수는 있다.
 *        미지의 것을 신비화하기보다 호기심을 유지하면서
 *        사실과 가능성을 차분히 살펴라.
 *    - [역위치 (Reversed)]
 *      · 상징: 비밀 누설, 운명의 장난, 도박 실패, 불확실성, 배신
 *      · 해석: 감춰진 정보가 드러나 신뢰가 흔들리거나,
 *        확률에 기대어 무리한 선택을 하고 있을 수 있다.
 *        불확실성을 견디지 못해 운이나 상대의 약속에 모든 것을 맡기지 말고,
 *        손실을 감당할 수 있는 범위를 먼저 정하라.
 *        비밀과 배신을 단정하기보다 확인 가능한 사실을 모으고
 *        중요한 정보와 경계를 신중히 지켜라.
 */
